#!/usr/bin/env python3
"""Generate mse.md using only Python's standard library, independently of spill.

Run: python3 tests/protocol/fixtures/mse_vectors.py > tests/protocol/fixtures/mse.md
"""

import hashlib

P = int(
    "FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD129024E088A67CC740"
    "20BBEA63B139B22514A08798E3404DDEF9519B3CD3A431B302B0A6DF25F1437"
    "4FE1356D6D51C245E485B576625E7EC6F44C42E9A63A36210000000000090563",
    16,
)
WIRE = bytes([17]) * 20
A = bytes(range(1, 21))
B = bytes(range(21, 41))
IA = b"\x13BitTorrent protocol" + bytes(8) + WIRE + bytes([65]) * 20
BT = b"\x13BitTorrent protocol" + bytes(8) + WIRE + bytes([66]) * 20
FRAME = b"\x00\x00\x00\x01\x02"


def sha(*parts):
    return hashlib.sha1(b"".join(parts)).digest()


class RC4:
    def __init__(self, key):
        self.s = list(range(256))
        j = 0
        for i in range(256):
            j = (j + self.s[i] + key[i % len(key)]) % 256
            self.s[i], self.s[j] = self.s[j], self.s[i]
        self.i = self.j = 0
        self.apply(bytes(1024))

    def apply(self, data):
        out = bytearray()
        for byte in data:
            self.i = (self.i + 1) % 256
            self.j = (self.j + self.s[self.i]) % 256
            self.s[self.i], self.s[self.j] = self.s[self.j], self.s[self.i]
            key = self.s[(self.s[self.i] + self.s[self.j]) % 256]
            out.append(byte ^ key)
        return bytes(out)


def vector(method):
    ya = pow(2, int.from_bytes(A, "big"), P).to_bytes(96, "big")
    yb = pow(2, int.from_bytes(B, "big"), P).to_bytes(96, "big")
    secret = pow(int.from_bytes(yb, "big"), int.from_bytes(A, "big"), P)
    secret = secret.to_bytes(96, "big")
    ca = RC4(sha(b"keyA", secret, WIRE))
    cb = RC4(sha(b"keyB", secret, WIRE))
    masked = bytes(x ^ y for x, y in zip(sha(b"req2", WIRE), sha(b"req3", secret)))
    header = bytes(8) + (3).to_bytes(4, "big") + bytes(2)
    header += len(IA).to_bytes(2, "big") + IA
    request = sha(b"req1", secret) + masked + ca.apply(header)
    reply = cb.apply(bytes(8) + method.to_bytes(4, "big") + bytes(2))
    app_a = ca.apply(FRAME) if method == 2 else FRAME
    app_b = cb.apply(BT + FRAME) if method == 2 else BT + FRAME
    padded_a = RC4(sha(b"keyA", secret, WIRE))
    padded_b = RC4(sha(b"keyB", secret, WIRE))
    padded_header = bytes(8) + (3).to_bytes(4, "big") + (512).to_bytes(2, "big")
    padded_header += bytes([119]) * 512 + len(IA).to_bytes(2, "big") + IA
    padded_request = sha(b"req1", secret) + masked + padded_a.apply(padded_header)
    padded_reply = bytes(8) + method.to_bytes(4, "big") + (512).to_bytes(2, "big")
    padded_reply = padded_b.apply(padded_reply + bytes([136]) * 512)
    return {
        "public_a": ya + bytes([85]) * 512,
        "public_b": yb + bytes([102]) * 512,
        "request": request,
        "reply": reply,
        "application_a": app_a,
        "application_b": app_b,
        "request_padded": padded_request,
        "reply_padded": padded_reply,
        "application_a_padded": padded_a.apply(FRAME) if method == 2 else FRAME,
        "application_b_padded": padded_b.apply(BT + FRAME) if method == 2 else BT + FRAME,
    }


print("# Independent MSE vectors\n")
print("Generated by `mse_vectors.py` with Python pow, hashlib and textbook RC4.")
print("The fixed modulus is the MSE modulus, not the Oakley group-1 modulus.")
print("Keys are bytes 1..20 and 21..40; wire key is 20 bytes of 0x11.")
print("Both public values have maximum legal 512-byte padding.\n")
for name, method in [("rc4", 2), ("plaintext", 1)]:
    for field, data in vector(method).items():
        print(f"{name}.{field}={data.hex()}")
